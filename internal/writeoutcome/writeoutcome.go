func init() {
	for k, t := range texts {
		t.Retry = retryAllowed[k]
		texts[k] = t
	}
}

// Describe — текст для исхода записи; ok == false — это не исход записи
// (Other): показывать прежним текстом ошибки, повтор не разрешён.
func Describe(err error) (Text, bool) {
	t, ok := texts[Classify(err)]
	return t, ok
}

// Message — полный текст для показа: что случилось, что делать, подробности
// (текст ядра: файл, код выхода, путь резервных копий).
func Message(t Text, err error) string {
	return t.What + "\n\n" + t.Next + "\n\nПодробности: " + err.Error()
}

// TextFor — текст исхода по виду (канарейка сверяет заголовок исхода, а не
// вольный текст). ok == false — вида нет.
func TextFor(k Kind) (Text, bool) {
	t, ok := texts[k]
	return t, ok
}

// All — все тексты исходов (для сторожей вида: запас ширины заголовка).
func All() []Text {
	out := make([]Text, 0, len(texts))
	for k := Other + 1; int(k) <= len(texts); k++ {
		out = append(out, texts[k])
	}
	return out
}

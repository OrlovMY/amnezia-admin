// Package writeoutcome — человеческие тексты исходов записи на сервер
// (A3б PR-3). Ядро (core/caswrite.go, core/txn.go) различает исходы типом
// ошибки; здесь — ЕДИНСТВЕННОЕ место того, что человек читает о каждом из
// них, общее для GUI и CLI: что случилось, записано ли, что делать дальше, и
// можно ли повторить тот же план. Пакет без Fyne: тексты сверяются таблицей.
//
// Правило CLAUDE.md «незнание не выдаётся за знание»: исходы «неизвестно,
// записано ли», «записано частично», «записано, откат не выполнен /
// неизвестен» не называются ни «не записано», ни «записано и всё в порядке».
//
// Повтор того же плана — ЗАКРЫТЫМ СПИСКОМ (раунд 4, AU-LOGIC Н-2): только
// исходы, где запись ДОКАЗАННО не начиналась и план не устарел. Всё прочее,
// включая неклассифицированное (Other), — без повтора.
package writeoutcome

import (
	"errors"

	"amnezia-admin/core"
)

// Kind — исход записи, отличный от «записано».
type Kind int

const (
	// Other — не исход записи (ошибка вне пути Apply: подключение, чтение
	// плана). На пути Apply таких нет — это держит сторож TestApplyErrorsClassified.
	Other Kind = iota
	Changed
	Busy
	ToolMissing
	LockUnavailable
	NotStarted
	Unknown
	Partial
	RollbackForeign
	RollbackNotDone
	RollbackUnknown
	RolledBack
	RolledBackNotApplied
	// Раунд 5 (AU-LOGIC Н-4): прежний RolledBackNotApplied сводил три
	// состояния; «не проверено» и «файлы не совпали» — отдельно.
	RollbackUnverified
	RolledBackFilesDiffer
	// SudoDenied — H1 (раунд 6 ядра): docker без sudo недоступен, sudo не
	// разрешил запустить docker; запись не начиналась, но повтор без правки
	// sudoers бесполезен — Retry=false (SEC-01 У1).
	SudoDenied
)

// Classify — исход по ошибке. Порядок ветвей — часть решения (признак 3):
// исходы отката стоят ВЫШЕ всего — их ошибка оборачивает и исход отката
// («занято», «неизвестно»…), и errors.Is видит его тоже; ниже — частные
// случаи раньше общих (частично — раньше неизвестно, замок — раньше нет
// утилиты).
func Classify(err error) Kind {
	switch {
	case err == nil:
		return Other
	case errors.Is(err, core.ErrRollbackForeign):
		return RollbackForeign
	case errors.Is(err, core.ErrRollbackNotDone):
		return RollbackNotDone
	case errors.Is(err, core.ErrRollbackUnknown):
		return RollbackUnknown
	case errors.Is(err, core.ErrRolledBackNotApplied):
		return RolledBackNotApplied
	case errors.Is(err, core.ErrRollbackUnverified):
		return RollbackUnverified
	case errors.Is(err, core.ErrRolledBackFilesDiffer):
		return RolledBackFilesDiffer
	case errors.Is(err, core.ErrRolledBack):
		return RolledBack
	// H1 (SEC-01 У1): отказ sudo — свой исход, выше общих случаев записи.
	case errors.Is(err, core.ErrSudoDenied):
		return SudoDenied
	case errors.Is(err, core.ErrWritePartial):
		return Partial
	case errors.Is(err, core.ErrWriteUnknown):
		return Unknown
	case errors.Is(err, core.ErrCASMismatch):
		return Changed
	case errors.Is(err, core.ErrServerBusy):
		return Busy
	case errors.Is(err, core.ErrLockUnavailable):
		return LockUnavailable
	case errors.Is(err, core.ErrServerToolMissing):
		return ToolMissing
	case errors.Is(err, core.ErrWriteNotStarted):
		return NotStarted
	}
	return Other
}

// Text — что показать человеку.
type Text struct {
	// Title — заголовок: одна короткая фраза.
	Title string
	// What — что случилось и записано ли.
	What string
	// Next — что делать дальше.
	Next string
	// Retry — безвреден ли повтор ТОГО ЖЕ плана (кнопка «Применить» в окне
	// изменений остаётся активной). Задаётся не здесь, а закрытым списком
	// retryAllowed.
	Retry bool
}

// retryAllowed — ЗАКРЫТЫЙ список исходов, где повтор того же плана
// безвреден: запись доказанно не начиналась (сверка и замена не шли, либо
// шли, но отказали до первой замены), и план не устарел. «Изменён другим» —
// не начиналась, но план устарел: повтор провалится тем же.
var retryAllowed = map[Kind]bool{Busy: true, ToolMissing: true, LockUnavailable: true, NotStarted: true}


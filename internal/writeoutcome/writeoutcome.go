// Describe — текст для исхода записи; ok == false — это не исход записи
// (Other), показывать прежним текстом ошибки.
func Describe(err error) (Text, bool) {
	t, ok := texts[Classify(err)]
	return t, ok
}

// Message — полный текст для показа: что случилось, что делать, подробности
// (текст ядра: файл, код выхода, путь резервных копий).
func Message(t Text, err error) string {
	return t.What + "\n\n" + t.Next + "\n\nПодробности: " + err.Error()
}

// Package writeoutcome — человеческие тексты исходов записи на сервер
// (A3б PR-3). Ядро (core/caswrite.go) различает исходы типом ошибки; здесь —
// ЕДИНСТВЕННОЕ место того, что человек читает о каждом из них, общее для GUI
// и CLI: что случилось, записано ли, что делать дальше, и можно ли повторить
// тот же план. Пакет без Fyne: тексты сверяются таблицей, а не окном.
//
// Правило CLAUDE.md «незнание не выдаётся за знание»: исходы «неизвестно,
// записано ли» и «записано частично» не называются ни «не записано», ни
// «записано», и повтор того же плана для них закрыт — повтор безвреден только
// там, где ничего не записано.
package writeoutcome

import (
	"errors"

	"amnezia-admin/core"
)

// Kind — исход записи, отличный от «записано».
type Kind int

const (
	// Other — не исход записи (сеть до записи, отказ плана и т.п.):
	// показывается прежним текстом ошибки.
	Other Kind = iota
	Changed
	Busy
	ToolMissing
	LockUnavailable
	Unknown
	Partial
	RollbackForeign
)

// Classify — исход по ошибке. Порядок ветвей — часть решения (признак 3):
// частные случаи (замок, частично, чужое после отката) стоят ВЫШЕ общих,
// которым они тоже равны по errors.Is.
func Classify(err error) Kind {
	switch {
	case err == nil:
		return Other
	case errors.Is(err, core.ErrRollbackForeign):
		return RollbackForeign
	case errors.Is(err, core.ErrWritePartial):
		return Partial
	case errors.Is(err, core.ErrWriteUnknown):
		return Unknown
	case errors.Is(err, core.ErrCASMismatch):
		return Changed
	case errors.Is(err, core.ErrServerBusy):
		return Busy
	case errors.Is(err, core.ErrLockUnavailable):
		return LockUnavailable
	case errors.Is(err, core.ErrServerToolMissing):
		return ToolMissing
	}
	return Other
}

// Text — что показать человеку.
type Text struct {
	// Title — заголовок: одна короткая фраза.
	Title string
	// What — что случилось и записано ли.
	What string
	// Next — что делать дальше.
	Next string
	// Retry — безвреден ли повтор ТОГО ЖЕ плана (кнопка «Применить» в окне
	// изменений остаётся активной). Только там, где точно ничего не записано
	// и план не устарел.
	Retry bool
}


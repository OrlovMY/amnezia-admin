package kbdlayout

// forceEnglish на Linux и macOS — ЧЕСТНАЯ ПУСТЫШКА, а не тихое «ничего не
// делаю и делаю вид, что сделал».
//
// ПОЧЕМУ ТАК, А НЕ «ПОТОМ НАПИШЕМ». Раскладкой на этих ОС владеет не
// приложение:
//   - Linux: раскладку держит сервер ввода (X11 — XKB через оконный
//     менеджер, Wayland — композитор), и внешняя программа может разве что
//     дёрнуть setxkbmap/gsettings, то есть ПЕРЕНАСТРОИТЬ систему человеку,
//     а не переключить ввод на время диалога. Запускать чужие утилиты ради
//     этого мы не будем;
//   - macOS: смена источника ввода — приватный API (TISSelectInputSource
//     публичен лишь для чтения и требует прав), приложениям Apple это
//     намеренно не отдаёт.
//
// Поэтому здесь возвращается ErrUnsupported — «точно нет», отличимое от
// «пытались и не смогли». Человека на этих ОС защищает кроссплатформенная
// страховка: core.NonEnglishLayoutSuspect и подсказка про раскладку.
func forceEnglish() error { return ErrUnsupported }

// windowStationName — понятия «оконная станция» вне Windows нет. Отвечает
// ErrUnsupported, чтобы проверка не гадала, а видела: спрашивать негде.
func windowStationName() (string, error) { return "", ErrUnsupported }

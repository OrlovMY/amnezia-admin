// Package kbdlayout переключает раскладку клавиатуры на английскую перед
// вводом пин-кода и админского ключа.
//
// ЗАЧЕМ. Просьба владельца 23.09.2026 дословно: «А еще ты можешь
// принудительно менять раскладку на английскую при введении паролей и
// пин-кодов. Как при первом вводе их, так и потом для авторизации?» Это не
// удобство: core.ValidatePin допускает только печатаемый ASCII, а символы в
// поле пароля скрыты — пин, набранный в русской раскладке, даёт отказ,
// причину которого человеку не видно.
//
// ТРИ СОСТОЯНИЯ, А НЕ ДВА (CLAUDE.md, «незнание не выдаётся за знание»):
//
//	err == nil                      — раскладка переключена;
//	errors.Is(err, ErrUnsupported)  — ЗНАЕМ, что на этой ОС так не умеем
//	                                  (Linux/macOS): не пытались и не делаем
//	                                  вид, что получилось;
//	любая другая ошибка             — пытались и НЕ СМОГЛИ; вызывающий обязан
//	                                  отличать это от успеха.
//
// СТРАХОВКА, КОТОРАЯ РАБОТАЕТ ВЕЗДЕ, живёт не здесь, а в
// core.NonEnglishLayoutSuspect: что бы ни вернула эта функция, во введённом
// тексте проверяется наличие символов вне набора, допустимого ValidatePin, и
// человеку говорится про раскладку. Она не зависит от успеха переключения и
// одинаково работает на всех ОС.
package kbdlayout

import "errors"

// ErrUnsupported — на этой ОС программная смена раскладки не делается.
// Это ЗНАНИЕ («точно нет»), а не неудача попытки.
var ErrUnsupported = errors.New("программное переключение раскладки на этой ОС не поддерживается")

// ForceEnglish переключает раскладку клавиатуры на английскую (США).
//
// Прежняя раскладка НЕ ВОССТАНАВЛИВАЕТСЯ после закрытия диалога: неожиданный
// возврат раскладки удивил бы сильнее, чем её отсутствие, — человек
// переключит сам, когда она ему понадобится (решение и довод — в отчёте
// GUI-доделок).
func ForceEnglish() error { return forceEnglish() }

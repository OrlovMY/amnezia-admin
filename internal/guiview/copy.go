// Копирование данных из таблицы пользователей (задание GUI-КОПИРОВАНИЕ,
// живая приёмка v0.2.0). Здесь живёт ВЕСЬ ответ на вопрос «что именно
// попадёт в буфер обмена» — в cmd/gui остаётся только показ меню и запись в
// буфер. Довод тот же, что у ActivityText/TrafficText в unknown.go: в
// cmd/gui строку не проверяет ни один тест без дисплея.
//
// ОДИН ИСТОЧНИК ТЕКСТА ЯЧЕЙКИ. CellText — единственное место, где решается
// содержимое ячейки таблицы, и cmd/gui рисует ячейки ею же. Иначе «что
// видно» и «что копируется» разъезжаются молча: видно «?», а копируется
// «0 B / 0 B».

// CopyColumnCount — число колонок таблицы пользователей. Совпадает с
// tableHeaders в cmd/gui; расхождение роняет сторож copyguard_test.go.
const CopyColumnCount = 6

// CreatedCellRunes — сколько рун даты создания помещается в ячейку
// («2026-09-22T12:34:56» — 19). Обрезка ВИЗУАЛЬНАЯ: в буфер по правилу
// задания уходит полное значение, см. CopyValue.
const CreatedCellRunes = 19

// RowSeparator — разделитель полей в «Копировать строку». Выбран « | », а не
// табуляция: строка вставляется в переписку и в заметку, где табуляция либо
// съедается, либо превращается в невидимый прыжок. Пример дословно:
//
//	3 | Ноутбук | 2026-09-22T12:34:56.789Z | 2 минуты назад | 1.2 MB / 900.0 KB | aBcD…=
const RowSeparator = " | "

// Row — данные ОДНОЙ строки таблицы: ровно то, из чего cmd/gui рисует
// ячейки. Признаки «не удалось» здесь отдельными полями, а не выводятся из
// пустоты значений (CLAUDE.md, признак 2).
type Row struct {
	// Num — номер строки, как он показан в первой колонке (с единицы).
	Num int
	// Name — имя клиента.
	Name string
	// Created — дата создания ЦЕЛИКОМ, как её вернул core.
	Created string
	// ClientID — публичный ключ клиента целиком (44 знака base64 для
	// WireGuard). Секретом не является: приватный ключ и vpn://-ключ в
	// таблицу не попадают и в Row не передаются.
	ClientID string
	// Disabled — запись отключена.
	Disabled bool
	// CanManage — управляемый протокол: статистика вообще запрашивалась.
	CanManage bool
	// ActivityFailed — запрос активности был и НЕ УДАЛСЯ.
	ActivityFailed bool
	// StatsFailed — запрос трафика был и НЕ УДАЛСЯ.
	StatsFailed bool
	// Handshake — значение активности из ответа сервера ("" — ключа в
	// ответе нет).
	Handshake string
	// Stats — измеренный трафик; осмыслен только при !StatsFailed.
	Stats core.PeerStat
}

// CellText — текст ячейки (row, col) таблицы пользователей, ровно тот, что
// человек видит на экране. Колонка вне диапазона — пустая строка.
func CellText(r Row, col int) string {
	switch col {
	case 0:
		return fmt.Sprintf("%d", r.Num)
	case 1:
		return r.Name
	case 2:
		if rs := []rune(r.Created); len(rs) > CreatedCellRunes {
			return string(rs[:CreatedCellRunes])
		}
		return r.Created
	case 3:
		return ActivityText(r.CanManage, r.ActivityFailed, r.Disabled, r.Handshake)
	case 4:
		return TrafficText(r.CanManage, r.StatsFailed, r.Stats)
	case 5:
		return r.ClientID
	}
	return ""
}

// CopyValue — что кладётся в буфер по пункту «Копировать значение».
//
// ДВА РЕШЕНИЯ, КОТОРЫЕ ЗДЕСЬ ПРИНЯТЫ И КОТОРЫЕ НАДО ЗНАТЬ.
//
//  1. Полное значение, а не обрезанное. Отличие от CellText ровно одно —
//     колонка «Создан»: на экране она урезана до CreatedCellRunes, в буфер
//     уходит дата целиком. Это прямое требование задания «копируется полное
//     значение, даже если в ячейке оно визуально обрезано».
//
//  2. «?» КОПИРУЕТСЯ КАК «?». Соблазн подставить в буфер «0 B / 0 B» или
//     пустую строку вместо «?» — это ровно то, против чего написан CLAUDE.md:
//     человек вставит строку в переписку, и незнание уедет туда измеренным
//     нулём. В буфер попадает то же, что видно: «—» (не спрашивали), «?»
//     (спрашивали и не узнали), «отключён» — каждое означает своё.
func CopyValue(r Row, col int) string {
	if col == 2 {
		return r.Created
	}
	return CellText(r, col)
}

// CopyRow — что кладётся в буфер по пункту «Копировать строку»: все колонки
// через RowSeparator, ОДНОЙ строкой и теми же значениями, что CopyValue.
// Ничего сверх видимого в таблице в неё не добавляется.
func CopyRow(r Row) string {
	parts := make([]string, 0, CopyColumnCount)
	for c := 0; c < CopyColumnCount; c++ {
		parts = append(parts, CopyValue(r, c))
	}
	return strings.Join(parts, RowSeparator)
}


// Незнание не выдаётся за знание (CLAUDE.md, задание A1): тексты GUI, у
// которых состояний ТРИ — «есть», «нет» и «узнать не удалось».
//
// ПОЧЕМУ ЭТИ ДВЕ ФУНКЦИИ ЖИВУТ ЗДЕСЬ, А НЕ В cmd/gui. В cmd/gui нет ни
// одного исполняемого теста: пакет тянет Fyne и cgo, а запуск требует
// дисплея. Строка, написанная там, не проверяется ничем — тем же доводом в
// этот пакет вынесены решения ViewState (FIX-VIEW) и текст предупреждения о
// гонке (A3а). Что cmd/gui зовёт именно их и именно на свежих данных,
// доказывает структурный сторож cardguard_test.go.

// Дословные тексты карточки удаления (UI-01/UX-01). Вынесены в константы,
// потому что тест различения сравнивает их ЦЕЛИКОМ, а не по вхождению.
const (
	// cardActivityWas — у клиента была активность. Восклицательный знак и
	// значок сохранены от прежней редакции cmd/gui/main.go дословно.
	cardActivityWas = "⚠ У этого клиента была активность!\nПоследнее подключение: %s"
	// cardActivityNone — сервер ответил, и ответ означает «не подключался».
	cardActivityNone = "Подключений не было."
	// cardActivityUnknown — ТРЕТЬЕ состояние, ради которого написан A1.
	// Раньше этот случай попадал в cardActivityNone, и человек удалял
	// работающего клиента, прочитав «подключений не было».
	// Второй строкой сказано не «произошла ошибка», а что именно осталось
	// неизвестным: решение принимает человек, и ему нужен предмет незнания,
	// а не код возврата.
	cardActivityUnknown = "Не удалось получить данные о подключениях.\n" +
		"Неизвестно, пользуется ли клиент этим доступом прямо сейчас."
	// cardActivityAbsent — сервер ответил, но этого клиента в ответе нет
	// (задание НЕЗНАНИЕ-ТРАФИК, место № 4). Раньше этот случай печатался
	// как cardActivityNone: пропущенный ключ карты читался пустой строкой.
	// Первая строка — то, что из ответа ИЗВЕСТНО (работающий wg клиента не
	// держит, значит, подключиться сейчас он не может); вторая — то, что
	// неизвестно. Отдельный текст, а не cardActivityUnknown: запрос не
	// провалился, и «не удалось получить данные» было бы неправдой.
	cardActivityAbsent = "Клиента нет в статистике сервера: сейчас сервер его не принимает.\n" +
		"Были ли подключения раньше — неизвестно."
)

// DeleteCardActivity — строка активности в карточке удаления GUI.
//
// err ПЕРЕВЕШИВАЕТ содержимое hs: при отказе сервера карта может прийти
// пустой или частично заполненной, и читать её означало бы снова выдавать
// незнание за «нет». Порядок ветвей здесь — часть правила, а не стиль
// (признак 3 правила П-НЕЗНАНИЕ: частный случай выше общего перехватывает
// «не знаем»).
func DeleteCardActivity(hs map[string]string, clientID string, err error) string {
	if err != nil {
		return cardActivityUnknown
	}
	v, ok := hs[clientID]
	switch {
	case !ok:
		return cardActivityAbsent
	case v != "" && v != "—":
		return fmt.Sprintf(cardActivityWas, v)
	}
	return cardActivityNone
}

// ActivityText — ячейка колонки «Активность» таблицы пользователей.
//
//	!canManage       → "—"        статистика не запрашивалась вовсе (нет `wg`
//	                              у XRay/DNS): "?" здесь означало бы «не
//	                              смогли узнать», а мы и не спрашивали;
//	disabled         → "отключён" состояние записи, а не измерение;
//	activityFailed   → "?"        запрос был и не удался;
//	hs == ""         → "?"        сервер ответил, но этого ключа в ответе
//	                              нет — про него мы тоже не знаем;
//	иначе            → значение из ответа ("—" = не подключался).
//
// Порядок ветвей — часть решения, а не стиль (признак 3 правила
// П-НЕЗНАНИЕ): частный случай выше общего перехватывал бы «не знаем».
// Текст живёт здесь, а не в cmd/gui, по тому же доводу, что и остальное в
// этом файле: в cmd/gui строку не проверяет ни один тест.
func ActivityText(canManage, activityFailed, disabled bool, hs string) string {
	switch {
	case !canManage:
		return "—"
	case disabled:
		return "отключён"
	case activityFailed:
		return "?"
	case hs == "":
		return "?"
	default:
		return hs
	}
}

// TrafficText — ячейка колонки «Трафик» таблицы пользователей.
//
//	!canManage          → "—"        статистика не запрашивалась вовсе (нет
//	                                 `wg` у XRay/DNS): «0 B» здесь означало
//	                                 бы измеренный ноль;
//	disabled            → "отключён" как в соседней колонке активности:
//	                                 отключённого peer'а в рантайме нет, и
//	                                 число о нём было бы выдумкой;
//	не PeerMeasured     → "?"        запрос не удался ИЛИ клиента нет в
//	                                 ответе сервера — в обоих случаях
//	                                 величина неизвестна;
//	иначе               → измеренные величины (в том числе честный ноль).
//
// ТРЕТЬЕ СОСТОЯНИЕ ВЫРАЖЕНО ТИПОМ (задание НЕЗНАНИЕ-ТРАФИК, место № 1).
// Прежняя сигнатура (canManage, statsFailed bool, st core.PeerStat) знала
// «запрос не удался», но не «клиента нет в ответе»: вызывающий брал
// st из карты по ключу, отсутствующий ключ давал нулевую PeerStat, и
// «0 B / 0 B» уезжал к человеку как измерение. core.PeerReading числа без
// признака «измерено» не отдаёт.
func TrafficText(canManage, disabled bool, r core.PeerReading) string {
	if !canManage {
		return "—"
	}
	if disabled {
		return "отключён"
	}
	st, ok := r.Measured()
	if !ok {
		return "?"
	}
	return core.HumanBytes(st.RxBytes) + " / " + core.HumanBytes(st.TxBytes)
}

// Тексты экрана подключения про сохранённые ключи (A1б). Здесь, а не в
// cmd/gui, по тому же доводу, что и остальное в пакете: строку в cmd/gui
// сверяет только тест с окном, а решение «какой номер назвать» — чистое.

// VaultListUnreadable — подпись на месте блока «Или загрузить из
// сохранённых», когда каталог сохранённых ключей прочитать не удалось.
// Прежде этот случай выглядел как «сохранённых ключей нет»: блок просто не
// появлялся (признак 2 правила П-НЕЗНАНИЕ).
func VaultListUnreadable(err error) string {
	return fmt.Sprintf("Сохранённые ключи прочитать не удалось: %v. Есть ли они — неизвестно; ключ можно вставить вручную.", err)
}

// SavedKeyStatus — строка состояния после сохранения ключа. Номер «Сервер N»
// — тот, под которым ИМЕННО ЭТОТ файл показан в списке сохранённых
// (savedVaultsBlock нумерует по порядку ListVaults). Прежде здесь стояло
// число файлов: имена файлов случайные, новый файл встаёт в любое место
// списка, и названный номер указывал на ДРУГОЙ сервер — а при нечитаемом
// каталоге получался «Сервер 0».
//
//	файл найден в списке       → «Ключ сохранён (Сервер N).»
//	список не прочитан / файла
//	в нём нет                  → «Ключ сохранён.» и что номер неизвестен.
func SavedKeyStatus(vaults []string, listErr error, savedPath string) string {
	if listErr == nil && savedPath != "" {
		want := filepath.Clean(savedPath)
		for i, p := range vaults {
			if filepath.Clean(p) == want {
				return fmt.Sprintf("Ключ сохранён (Сервер %d).", i+1)
			}
		}
	}
	return "Ключ сохранён. Под каким номером он в списке сохранённых — определить не удалось."
}

// PinThrottleUnknown — текст диалога пин-кода, когда счётчик неверных
// попыток не удалось прочитать или записать (долг Н8). Ввод пина при этом
// закрыт: пустить с предупреждением значило бы, что любой сбой записи
// снимает ограничение попыток, а человек этого не заметит (SEC-01).
// Причина и путь — прямо; путь не секрет (решение владельца 19.09).
func PinThrottleUnknown(err error) string {
	// Раунд 3 (UX-01, В1-б): главное — что ввод закрыт и что нажать — в
	// начале: полоса состояния показывает две строки (~100 знаков), путь
	// бывает длиннее 170 знаков и уходит под прокрутку в конце. Текст ревью
	// («Проверьте права … и нажмите «Повторить».») в 100 знаков не
	// укладывался (139); итоговая формулировка UX-01 — «Повторить» на 92-м.
	op, advice, tail := "прочитать или сохранить", "проверьте, доступна ли папка программы для записи", "Причина: "+err.Error()+"."
	var te *core.ThrottleError
	if errors.As(err, &te) {
		op, tail = te.Op, "Причина: "+te.Reason()+". Файл: "+te.Path+"."
		// Раунд 4 (AU-LOGIC Н-1): совет — по сути того пути, что назван.
		// «Удалите» — только если это файл и он повреждён.
		switch te.Fault {
		case core.FaultCorrupt:
			advice = "удалите его, он повреждён"
		case core.FaultIsDir:
			advice = "на месте файла — папка, переименуйте или удалите её"
		case core.FaultDenied:
			advice = "у программы нет прав на него — снимите «только чтение» или проверьте права папки"
		}
	}
	return fmt.Sprintf("Ввод пина закрыт: не удалось %s счётчик попыток. "+
		"Проверьте файл и нажмите «Повторить»: %s. %s", op, advice, tail)
}

// Предупреждение о гонке при одновременной работе (A3а).
//
// ВТОРОЙ ПРЕДМЕТ ЭТОГО ПАКЕТА. В guiview.go живёт первый — решения GUI "что
// грузить / что показывать / доступно ли управление" по контейнеру (FIX-VIEW).
// Здесь — тексты предупреждения о гонке и решение "показывать или молчать"
// (A3а). Почему два предмета в одном пакете, а не новый каталог: обе темы
// суть "решения GUI без Fyne, предъявляемые тестом", а новый пакет ради двух
// функций дороже, чем вторая тема в существующем пакете без Fyne и без CGO,
// который cmd/gui уже импортирует. Третий предмет сюда не добавляют не
// подумав: признак, что предмет сюда подходит, — он решается чистой функцией
// и проверяется таблицей.
//
// Зачем предмет существует. Проверка контрольной суммы и запись на сервер
// выполняются отдельными SSH-вызовами, мьютекс защищает только собственный
// процесс: две программы или два окна, работающие с одним сервером, дают
// потерянное обновление — обоим сказано "готово", один клиент молча стёрт, и
// ему выдан рабочий на вид файл настроек, который не работает. Починка —
// отдельная работа (A3б, серверная блокировка). Пока она не сделана,
// программа обязана предупреждать; предупреждение снимается при слиянии A3б,
// потому что предупреждение о починенном дефекте — новое неверное
// утверждение.
//
// Границы предмета, названные прямо. Здесь решается, ЧТО сказать и КОГДА
// сказать. Показ (диалог, кнопки, модальность) — за cmd/gui: этот пакет без
// Fyne, и в нём нельзя ни построить диалог, ни доказать, что он появился.
// Что вызов предупреждения написан в каждом обработчике — доказывает сторож
// warnguard_test.go; что диалог срабатывает на живом экране — не доказывает
// здесь ничто, это проверка владельца.
package guiview

// Op — вид действия GUI, о котором спрашивают у WarnDecision. Перечислены и
// изменяющие операции, и просмотровые: правило "молчать, пока ничего не
// меняют" проверяется таблицей только тогда, когда просмотр в ней назван
// поимённо, а не подразумевается отсутствием.
type Op int

const (
	// Просмотр — ничего не меняется ни на сервере, ни локально.
	OpOpenApp      Op = iota // запуск программы
	OpSelectServer           // выбор сервера/контейнера
	OpRefreshList            // кнопка "Обновить"
	OpShowDiff               // "Показать изменения" — чтение плана
	OpShowConfig             // просмотр готового конфига

	// Изменение — необратимая запись на сервер.
	OpAddUser    // создать пользователя
	OpRenameUser // переименовать
	OpToggleUser // включить/выключить
	OpRekeyUser  // перевыпустить конфиг
	OpDeleteUser // удалить пользователя
	// OpApplyPlan — применение подготовленного плана из окна "Изменения
	// перед применением" (кнопка "Применить"). ШЕСТАЯ точка записи, и у неё
	// СВОЙ смысл, а не смысл одной из пяти: человек здесь применяет план,
	// построенный РАНЬШЕ, и промежуток между построением плана и записью —
	// то самое окно, в которое вклинивается вторая программа. Ни одну из
	// пяти констант сюда переиспользовать нельзя: в таблице должно быть
	// видно, что путь другой.
	//
	// Путь этот выбирает самый осторожный человек — тот, кто сначала
	// смотрит, что изменится, и только потом применяет. Без этой константы
	// именно он остался бы без предупреждения. Окно изменений — вдобавок
	// ЕДИНСТВЕННОЕ место продукта, где гонка засвидетельствована кодом: там
	// уже обрабатывается отказ CAS словами "План устарел: сервер изменился,
	// пока окно было открыто".
	OpApplyPlan
)

// opNames — подписи операций для сообщений тестов и сторожа.
var opNames = map[Op]string{
	OpOpenApp:      "запуск программы",
	OpSelectServer: "выбор сервера",
	OpRefreshList:  "обновление списка",
	OpShowDiff:     "показ изменений",
	OpShowConfig:   "просмотр конфига",
	OpAddUser:      "создание",
	OpRenameUser:   "переименование",
	OpToggleUser:   "включение/выключение",
	OpRekeyUser:    "перевыпуск конфига",
	OpDeleteUser:   "удаление",
	OpApplyPlan:    "применение подготовленного плана",
}

func (o Op) String() string {
	if s, ok := opNames[o]; ok {
		return s
	}
	return "неизвестная операция"
}

// ChangesServer — меняет ли операция что-нибудь на сервере. Третьего
// состояния здесь нет по существу: перечень операций закрыт и известен
// целиком, неизвестная операция считается ИЗМЕНЯЮЩЕЙ — в сомнении
// предупредить дешевле, чем промолчать перед потерей данных.
func (o Op) ChangesServer() bool {
	switch o {
	case OpOpenApp, OpSelectServer, OpRefreshList, OpShowDiff, OpShowConfig:
		return false
	default:
		return true
	}
}

// WarnFrequency — режим частоты показа. Владелец 18.09.2026 выбрал
// WarnOncePerRun; WarnEveryTime остаётся вторым значением параметра, а не
// мёртвой веткой: оба режима прогоняются таблицей TestWarnDecision, и смена
// решения владельца стоит одной строки вызова в cmd/gui, а не переделки.
type WarnFrequency int

const (
	// WarnOncePerRun — предупредить один раз за запуск программы; счётчик
	// сбрасывается при смене сервера. Значение по умолчанию.
	WarnOncePerRun WarnFrequency = iota
	// WarnEveryTime — предупреждать перед каждым изменением.
	WarnEveryTime
)

// WarnSession — состояние "уже предупреждали в этом запуске и про какой
// сервер". ХРАНИТ ЕГО ВЫЗЫВАЮЩАЯ СТОРОНА (cmd/gui), пакет не хранит ничего:
// ни глобальной переменной, ни поля-синглтона. Причина не в чистоте, а в
// проверяемости — иначе строки таблицы TestWarnDecision начали бы зависеть
// от порядка прогона друг друга, и "смена сервера → показать снова"
// перестала бы быть независимой проверкой.
type WarnSession struct {
	// Warned — предупреждение уже показано в этом запуске.
	Warned bool
	// Server — сервер, для которого оно было показано.
	Server string
}

// AfterWarned — состояние сеанса после показа предупреждения про server.
// Возвращает новое значение, ничего не меняя на месте: вызывающая сторона
// присваивает его своему полю одной строкой.
func AfterWarned(server string) WarnSession {
	return WarnSession{Warned: true, Server: server}
}

// WarnDecision — показывать ли предупреждение перед операцией op на сервере
// server при режиме freq и состоянии сеанса sess. Чистая функция: весь вход
// в параметрах, состояние сеанса — тоже.
func WarnDecision(op Op, freq WarnFrequency, sess WarnSession, server string) bool {
	// Первое и главное: человек, который ничего не меняет, не видит ничего.
	// Решение владельца: "Если он ничего не трогает - молчать".
	if !op.ChangesServer() {
		return false
	}
	if freq == WarnEveryTime {
		return true
	}
	// WarnOncePerRun: показать, если в этом запуске ещё не предупреждали
	// либо предупреждали про ДРУГОЙ сервер. Сравнение по серверу — не
	// украшение: гонка возможна на каждом сервере отдельно, и человек,
	// перешедший на другой сервер, про новый ещё не предупреждён.
	return !sess.Warned || sess.Server != server
}

// warningTitle и warningBody — единственное место текста предупреждения.
// Дословно согласовано в задании A3а (Г1) и сверяется TestWarningTextGolden.
// Три обязательные части тела: (1) обстоятельства — две программы или два
// окна с одним сервером; (2) что произойдёт — изменения теряются молча,
// клиент исчезает, "готово" видят оба; (3) что делать — работать из одного
// места, а если работали из другого, обновить список.
//
// Каждое действие, к которому призывает текст, существует в интерфейсе под
// тем же словом: "обновите список" — кнопка "Обновить" (cmd/gui/main.go),
// "закройте изменение" — кнопка "Отмена" у всех пяти диалогов. Меняете
// формулировку совета — называйте кнопку так, как она подписана, иначе
// человек будет искать несуществующее.
//
// Строки "это временно, скоро починим" здесь нет намеренно: обещание в
// тексте продукта живёт дольше самой починки и превращается в новое неверное
// утверждение. Предупреждение снимается вместе с починкой гонки (A3б).
const (
	warningTitle = "Сейчас будет изменение на сервере"

	warningBody = "Если в это же время с этим сервером работает другая программа или другое окно — ваш администратор рядом или ваша же консольная версия, — изменения одного из вас будут потеряны молча: пользователь может исчезнуть из списка, выданные ему настройки перестанут работать, а «готово» увидят оба.\n\nРаботайте с сервером из одного места за раз. Если только что работали из другого — закройте изменение, обновите список и начните заново."
)

// WarningTitle — заголовок предупреждения (первая строка эталона Г1).
func WarningTitle() string {
	return warningTitle
}

// WarningBody — тело предупреждения: обстоятельства, что произойдёт, что делать.
func WarningBody() string {
	return warningBody
}

// WarningText — предупреждение целиком, готовое к показу: заголовок, пустая
// строка, тело. Дословно сверяется с эталоном задания (TestWarningTextGolden).
func WarningText() string {
	return warningTitle + "\n\n" + warningBody
}

// WarnContinueLabel и WarnCancelLabel — подписи кнопок предупреждения. Живут
// здесь по той же причине, что и текст: литерал в cmd/gui — это строка,
// которую не видит ни один тест. "Отмена" совпадает с подписью кнопки отказа
// всех пяти диалогов не случайно — текст советует "закройте изменение", и
// названное в совете действие обязано существовать под тем же словом.
func WarnContinueLabel() string { return "Продолжить" }
func WarnCancelLabel() string   { return "Отмена" }

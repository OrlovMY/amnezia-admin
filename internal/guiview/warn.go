package guiview

// Op — вид действия GUI, о котором спрашивают у WarnDecision. Перечислены и
// изменяющие операции, и просмотровые: правило "молчать, пока ничего не
// меняют" проверяется таблицей только тогда, когда просмотр в ней назван
// поимённо, а не подразумевается отсутствием.
type Op int

const (
	// Просмотр — ничего не меняется ни на сервере, ни локально.
	OpOpenApp      Op = iota // запуск программы
	OpSelectServer           // выбор сервера/контейнера
	OpRefreshList            // кнопка "Обновить"
	OpShowDiff               // "Показать изменения" — чтение плана
	OpShowConfig             // просмотр готового конфига

	// Изменение — необратимая запись на сервер.
	OpAddUser    // создать пользователя
	OpRenameUser // переименовать
	OpToggleUser // включить/выключить
	OpRekeyUser  // перевыпустить конфиг
	OpDeleteUser // удалить пользователя
)

// opNames — подписи операций для сообщений тестов и сторожа.
var opNames = map[Op]string{
	OpOpenApp:      "запуск программы",
	OpSelectServer: "выбор сервера",
	OpRefreshList:  "обновление списка",
	OpShowDiff:     "показ изменений",
	OpShowConfig:   "просмотр конфига",
	OpAddUser:      "создание",
	OpRenameUser:   "переименование",
	OpToggleUser:   "включение/выключение",
	OpRekeyUser:    "перевыпуск конфига",
	OpDeleteUser:   "удаление",
}

func (o Op) String() string {
	if s, ok := opNames[o]; ok {
		return s
	}
	return "неизвестная операция"
}

// ChangesServer — меняет ли операция что-нибудь на сервере. Третьего
// состояния здесь нет по существу: перечень операций закрыт и известен
// целиком, неизвестная операция считается ИЗМЕНЯЮЩЕЙ — в сомнении
// предупредить дешевле, чем промолчать перед потерей данных.
func (o Op) ChangesServer() bool {
	switch o {
	case OpOpenApp, OpSelectServer, OpRefreshList, OpShowDiff, OpShowConfig:
		return false
	default:
		return true
	}
}

// WarnFrequency — режим частоты показа. Владелец 18.09.2026 выбрал
// WarnOncePerRun; WarnEveryTime остаётся вторым значением параметра, а не
// мёртвой веткой: оба режима прогоняются таблицей TestWarnDecision, и смена
// решения владельца стоит одной строки вызова в cmd/gui, а не переделки.
type WarnFrequency int

const (
	// WarnOncePerRun — предупредить один раз за запуск программы; счётчик
	// сбрасывается при смене сервера. Значение по умолчанию.
	WarnOncePerRun WarnFrequency = iota
	// WarnEveryTime — предупреждать перед каждым изменением.
	WarnEveryTime
)

// WarnSession — состояние "уже предупреждали в этом запуске и про какой
// сервер". ХРАНИТ ЕГО ВЫЗЫВАЮЩАЯ СТОРОНА (cmd/gui), пакет не хранит ничего:
// ни глобальной переменной, ни поля-синглтона. Причина не в чистоте, а в
// проверяемости — иначе строки таблицы TestWarnDecision начали бы зависеть
// от порядка прогона друг друга, и "смена сервера → показать снова"
// перестала бы быть независимой проверкой.
type WarnSession struct {
	// Warned — предупреждение уже показано в этом запуске.
	Warned bool
	// Server — сервер, для которого оно было показано.
	Server string
}

// AfterWarned — состояние сеанса после показа предупреждения про server.
// Возвращает новое значение, ничего не меняя на месте: вызывающая сторона
// присваивает его своему полю одной строкой.
func AfterWarned(server string) WarnSession {
	return WarnSession{Warned: true, Server: server}
}


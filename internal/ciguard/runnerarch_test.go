// Файл runnerarch_test.go — сторож поля `arch` в матрице job build файла
// release.yml.
//
// Зачем он заведён. Аудит записал находку так: «ciguard не сравнивает arch:
// подмена arm64→amd64 в release.yml проходит зелёной». Подмена действительно
// проходит зелёной, но механизм назван неверно, и знать это важно, чтобы не
// чинить не то: `matrix.arch` не используется НИ ОДНИМ шагом release.yml
// (`grep -c "matrix.arch"` даёт 0), архитектуру собираемых файлов целиком
// задаёт scripts/build-release.sh жёстко. То есть подмена не отправила бы в
// релиз бинарь не под ту архитектуру — она вообще ничего не изменила бы в
// сборке.
//
// Дефект от этого не исчезает, он другой: `arch` — СПРАВОЧНОЕ поле, которое
// никто не сверяет с действительностью. Оно существует, чтобы человек,
// читающий workflow, знал, что macos-26 — это arm64. Разойдясь с
// действительностью (сменили метку раннера, добавили Intel-мак), оно будет
// уверенно врать читателю — то самое незнание, выданное за «всё в порядке»,
// только адресованное разработчику.
//
// Почему сверка идёт с таблицей в коде, а НЕ с scripts/build-release.sh.
// Комментарий над самой матрицей говорит прямо: «архитектура macOS-метки
// macos-26 — arm64». Значит `arch` — архитектура МАШИНЫ, на которой идёт job,
// а `GOARCH` в скрипте — архитектура ВЫХОДНЫХ ФАЙЛОВ. Это разные величины:
// ubuntu-24.04 (amd64) собирает и amd64, и arm64; macos-26 (arm64) собирает и
// arm64, и amd64. Правило «объявленный arch обязан входить в множество
// собираемых для этой ОС» на подмене из аудита дало бы PASS — подменённое
// amd64 в множество для macos ВХОДИТ; покраснеть оно могло бы только на
// windows, единственной односборочной ОС. Поэтому сверка здесь — РАВЕНСТВО
// объявленного значения значению из таблицы runnerArch, по образцу
// internal/envcheck/buildtargets_test.go: таблица в коде против записи в файле.
//
// Граница честности, которую этот сторож НЕ переходит и переходить не может.
// Он сверяет ДВЕ НАШИ ЗАПИСИ об одном факте: матрицу в release.yml и таблицу
// ниже. Ни одна из них не является измерением. Если GitHub сменит архитектуру
// образа, обе останутся согласованными и обе будут неверны. Единственная
// настоящая проверка — на самом раннере: шаг, сверяющий $RUNNER_ARCH с
// matrix.arch и роняющий job при расхождении. Он требует правки release.yml и
// потому передан в A6 обязательным следствием. Достижение этого файла
// формулируется так и не сильнее: «две наши записи об архитектуре раннера
// согласованы», а НЕ «поле arch верно».
//
// release.yml здесь только читается.
package ciguard

import (
	"os"
	"sort"
	"testing"

	"gopkg.in/yaml.v3"
)

// runnerArch — что проект знает об архитектуре закреплённых меток раннеров.
//
// Источник всех трёх строк — комментарий над матрицей в release.yml, перенесён
// дословно: «Закреплённые метки на 15.09.2026 —
// https://github.com/actions/runner-images#available-images (то, на что сейчас
// резолвятся *-latest); архитектура macOS-метки macos-26 — arm64 (см. Image
// Definitions macos-26-arm64-Readme.md)».
//
// Значения НИКЕМ не измерены — сети у проверяющих не было. Это знание проекта
// о чужих образах, и оно устаревает само, без единой правки у нас. Отсюда
// требование ниже: метка, которой здесь нет, роняет тест, а не пропускается.
// Добавляешь строку — добавляй и ссылку на Image Definitions, откуда взял.
var runnerArch = map[string]string{
	"ubuntu-24.04": "amd64",
	"windows-2025": "amd64",
	"macos-26":     "arm64",
}

// matrixEntriesOf возвращает элементы jobs.<job>.strategy.matrix.include
// указанного файла — и ниоткуда больше.
//
// Разбор настоящим YAML-разборщиком, а не построчными регулярками, по той же
// причине, что и в matrix_test.go: путь к данным задан структурой, а не тем,
// на что похожа строка. Сознательно отдельная функция, а не переиспользование
// matrixPairsOf: та возвращает склеенные пары os/runner и роняет тест на
// элементе без пары — здесь нужны сырые элементы, и ослаблять её ветки ради
// этого нельзя.
func matrixEntriesOf(t *testing.T, path, job string) []map[string]string {
	t.Helper()

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("не прочитать %s: %v", path, err)
	}

	var wf workflow
	if err := yaml.Unmarshal(data, &wf); err != nil {
		t.Fatalf("не разобрать %s как YAML: %v", path, err)
	}

	j, ok := wf.Jobs[job]
	if !ok {
		names := make([]string, 0, len(wf.Jobs))
		for name := range wf.Jobs {
			names = append(names, name)
		}
		sort.Strings(names)
		t.Fatalf("в %s нет job %q (есть: %v) — тест перестал что-либо проверять", path, job, names)
	}

	entries := j.Strategy.Matrix.Include

	// Пустая матрица зелёным быть не имеет права: если разбор перестал
	// находить элементы (переименовали ключ, перенесли матрицу, сменили форму
	// записи), сторож обязан покраснеть, а не отрапортовать, что сверять
	// нечего и всё в порядке.
	if len(entries) == 0 {
		t.Fatalf("в %s (job %s) не найдено ни одного элемента матрицы — тест перестал что-либо проверять", path, job)
	}
	return entries
}

// TestReleaseMatrixArchMatchesRunnerTable — объявленный в матрице arch обязан
// РАВНЯТЬСЯ тому, что таблица runnerArch говорит про объявленную метку.
//
// Три входа, на которых тест обязан упасть, а не промолчать:
//  1. не найдено ни одного элемента матрицы (в matrixEntriesOf);
//  2. элемент без ключа arch — сравнивать нечего;
//  3. метка раннера, которой нет в таблице runnerArch — сверять не с чем.
//
// Третий вход — главный для будущего: метки меняются чаще, чем поля arch.
// GitHub выведет macos-26 из обращения, кто-то поставит macos-27, таблица про
// него ничего не знает — и сторож, написанный небрежно, «не найдёт
// расхождения» и промолчит. Молчание про незнакомую метку превращает
// устаревание в зелёный цвет, а это ровно тот класс, ради которого сторож и
// писался.
func TestReleaseMatrixArchMatchesRunnerTable(t *testing.T) {
	const job = "build"
	for i, entry := range matrixEntriesOf(t, releaseYML, job) {
		runner, hasRunner := entry["runner"]
		if !hasRunner {
			t.Errorf("в %s (job %s) элемент матрицы №%d не содержит runner — сверять нечего: %v",
				releaseYML, job, i+1, entry)
			continue
		}

		declared, hasArch := entry["arch"]
		if !hasArch {
			t.Errorf("в %s (job %s) элемент матрицы №%d не содержит arch — сравнивать нечего (раннер %s)",
				releaseYML, job, i+1, runner)
			continue
		}

		want, known := runnerArch[runner]
		if !known {
			t.Errorf("метка раннера %s не описана в таблице runnerArch — сверять не с чем; "+
				"добавь строку с ссылкой на Image Definitions.\n"+
				"  Это не «совпало»: тест по этому элементу перестал что-либо проверять.\n"+
				"  %s (job %s), элемент матрицы №%d, объявлено arch: %s",
				runner, releaseYML, job, i+1, declared)
			continue
		}

		if declared != want {
			t.Errorf("в %s (job %s) для раннера %s объявлено arch: %s, таблица runnerArch говорит %s.\n"+
				"  Либо поле в матрице разошлось с тем, что проект знает о метке, либо устарела таблица —\n"+
				"  и тогда правится таблица вместе с ссылкой на Image Definitions, откуда взято новое значение.",
				releaseYML, job, runner, declared, want)
		}
	}
}

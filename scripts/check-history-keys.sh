#!/usr/bin/env bash
# scripts/check-history-keys.sh — есть ли в истории git НАСТОЯЩИЙ приватный
# ключ (шаг 1 RELEASING.md).
#
# Зачем отдельный скрипт, а не grep -c в инструкции. Прежняя проверка
# считала PEM-заголовки и ждала 0. С тестов маскировки
# (core/runner_mask_test.go) заголовков в истории больше десятка — это
# синтетические строки внутри Go-литералов, тела у них `test-pem-body-…`.
# Инструкция кричала «не публиковать» на каждом релизе, и такой крик
# быстро перестают слушать. Поднять ожидаемое число — значит ослабить
# проверку: настоящий ключ, добавленный пятнадцатым, прошёл бы молча.
#
# Различение по существу, а не по числу. У настоящего ключа сразу за
# заголовком идёт ТЕЛО — строка base64 (64 символа у PKCS#1/PKCS#8, 70 у
# OpenSSH). У синтетического заголовка тела нет: за ним `\n" + body`, код
# теста или текст. Поэтому подозрительным считается заголовок, в хвосте
# строки которого или в двух следующих строках есть непрерывный отрезок
# base64 длиной от 48 символов. Это ловит и ключ, вставленный как файл, и
# ключ, склеенный в одну строку через `\n` (в JSON, в Go-литерале).
#
# ГРАНИЦА. Ключ, у которого тело разбито на отрезки короче 48 символов или
# отнесено от заголовка дальше двух строк, этой проверкой не опознаётся.
# Поэтому скрипт печатает и общее число заголовков — человек видит, что их
# стало больше, чем было при прошлом выпуске (записано в RELEASING.md).
#
# Канарейка. Перед разбором истории скрипт прогоняет ТУ ЖЕ функцию на трёх
# образцах, собранных на лету (в тексте скрипта ключа нет — иначе скрипт
# нашёл бы сам себя): ключ файлом и ключ одной строкой обязаны опознаться,
# синтетический заголовок из тестов — нет. Иначе — выход 2: проверка не
# доказала, что работает.
#
# Выход: 0 — подозрительных нет; 1 — есть (печатаются заголовки и номера
# строк вывода git log, тела не печатаются никогда); 2 — канарейка.
#
# Использование:  bash scripts/check-history-keys.sh [ref]   (по умолчанию main)
set -euo pipefail

ref="${1:-main}"

# scan — читает вывод `git log -p` (или образец) со stdin, печатает
# "HEADERS <n>" и строки "SUSPECT <номер строки>: <заголовок>".
scan() {
	awk '
	function has_body(s,   n, i, parts) {
		gsub(/[^A-Za-z0-9+\/]/, " ", s)
		n = split(s, parts, " ")
		for (i = 1; i <= n; i++) if (length(parts[i]) >= 48) return 1
		return 0
	}
	{
		line = $0
		sub(/^[-+ ]/, "", line)
		if (window > 0) {
			window--
			if (!reported && has_body(line)) { print "SUSPECT " hdr_nr ": " hdr; reported = 1 }
		}
		if (match(line, /BEGIN [A-Z ]*PRIVATE KEY-----/)) {
			headers++
			hdr_nr = NR
			hdr = substr(line, RSTART, RLENGTH)
			reported = 0
			window = 2
			if (has_body(substr(line, RSTART + RLENGTH))) { print "SUSPECT " hdr_nr ": " hdr; reported = 1 }
		}
	}
	END { print "HEADERS " headers + 0 }
	'
}

count_suspects() { grep -c '^SUSPECT ' || true; }

# --- канарейка ---------------------------------------------------------------
begin="-----BEGIN OPENSSH PRIVATE"" KEY-----"
end="-----END OPENSSH PRIVATE"" KEY-----"
body="$(head -c 52 /dev/zero | base64 | tr -d '\n')" # 72 символа base64
[ "${#body}" -ge 48 ] || { echo "СТОП: канарейка не собралась — тело образца ${#body} символов" >&2; exit 2; }

as_file="$(printf '+%s\n+%s\n+%s\n' "$begin" "$body" "$end" | scan | count_suspects)"
one_line="$(printf '+\tkey := "%s\\n%s\\n%s"\n' "$begin" "$body" "$end" | scan | count_suspects)"
synthetic="$(printf '+\t\tin := "ssh: ключ отвергнут:\\n%s\\n" + body\n+\t\tgot := maskFreeText(in)\n' "$begin" | scan | count_suspects)"
if [ "$as_file" != 1 ] || [ "$one_line" != 1 ] || [ "$synthetic" != 0 ]; then
	echo "СТОП: канарейка — ключ файлом: $as_file (ждали 1), ключ строкой: $one_line (ждали 1), синтетический заголовок: $synthetic (ждали 0)." >&2
	echo "Проверка не доказала, что различает ключ и заголовок; её результату верить нельзя." >&2
	exit 2
fi

# --- история -----------------------------------------------------------------
out="$(git -c core.quotePath=false log "$ref" -p | scan)"
headers="$(printf '%s\n' "$out" | sed -n 's/^HEADERS //p')"
suspects="$(printf '%s\n' "$out" | count_suspects)"
echo "канарейка: ключ файлом и ключ строкой опознаны, синтетический заголовок — нет"
echo "PEM-заголовков приватного ключа в истории $ref: $headers"
echo "из них с телом ключа рядом (подозрительных): $suspects"
if [ "$suspects" != 0 ]; then
	printf '%s\n' "$out" | grep '^SUSPECT ' >&2
	echo "СТОП: рядом с заголовком найдено тело ключа. Не публиковать, звать ядро." >&2
	exit 1
fi

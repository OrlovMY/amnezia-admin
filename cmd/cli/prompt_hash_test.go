package main

import (
	"os"
	"strings"
	"testing"
)

// TestMenuPromptsSayHashForm — подсказки ввода четырёх пунктов меню говорят о
// смене привычки ПРЯМО (ревью UX-01, 29.09.2026): «#3» — номер строки, а
// просто «3» — имя. Решение владельца 26.09.2026 поменяло смысл голого числа;
// подсказка, которая говорит только примером, эту смену прячет.
//
// Сторож по исходнику: ask() печатает в терминал, и подсказка — литерал в
// main.go. Счёт — ровно четыре: пункты «удалить», «переименовать»,
// «отключить/включить», «перевыпустить».
func TestMenuPromptsSayHashForm(t *testing.T) {
	src, err := os.ReadFile("main.go")
	if err != nil {
		t.Fatal(err)
	}
	const want = "(имя, публичный ключ или номер строки: #3; просто «3» — это имя): "
	if n := strings.Count(string(src), want); n != 4 {
		t.Errorf("подсказок с прямым текстом о «#3» и «3» в main.go: %d, ожидалось 4", n)
	}
	if n := strings.Count(string(src), "или номер строки)"); n != 0 {
		t.Errorf("осталось %d старых подсказок «…или номер строки)» — без решётки", n)
	}
}
